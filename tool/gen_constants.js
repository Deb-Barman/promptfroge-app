// Generates lib/core/constants_data.dart from the ORIGINAL PromptForge.html (CONFIG + persona/audience tables).
// Usage: node tool/gen_constants.js path/to/PromptForge.html > lib/core/constants_data.dart
const fs = require('fs');
const vm = require('vm');
const html = fs.readFileSync(process.argv[2], 'utf8').split('\n');
const start = html.findIndex(l => l.startsWith('const CONFIG = {'));
let end = start;
while (!(html[end] === '};')) end++;
const cfgSrc = html.slice(start, end + 1).join('\n');
const ctx = {};
vm.createContext(ctx);
vm.runInContext(cfgSrc + '\nthis.CONFIG = CONFIG;', ctx);
const C = ctx.CONFIG;

const joined = html.join('\n');
function grabArray(name) {
  const i = joined.indexOf(name + ': [');
  const j = joined.indexOf('\n  ],', i);
  const src = joined.slice(i + name.length + 2, j + 4);
  return vm.runInNewContext('(' + src.trim().replace(/,$/, '') + ')');
}
const PERSONAS = grabArray('PERSONAS');
const AUDIENCES = grabArray('AUDIENCES');

const colorVars = {
  'var(--text-tertiary)': 0xFF7A8290, 'var(--accent-green)': 0xFF4FAE7A, 'var(--accent-blue)': 0xFF5B8DEF,
  'var(--accent-violet)': 0xFF9B7FE0, 'var(--accent-amber)': 0xFFE8A33D, 'var(--accent-red)': 0xFFE55A5A,
  'var(--dna-role)': 0xFFE8A33D, 'var(--dna-context)': 0xFF5B8DEF, 'var(--dna-objective)': 0xFF9B7FE0,
  'var(--dna-task)': 0xFF4FAE7A, 'var(--dna-instructions)': 0xFF4FC3D9, 'var(--dna-constraints)': 0xFFE55A5A,
  'var(--dna-examples)': 0xFFD97BD0, 'var(--dna-input)': 0xFF7FB3E0, 'var(--dna-output)': 0xFFE8A33D,
  'var(--dna-evaluation)': 0xFFC9A15A, 'var(--dna-edgecases)': 0xFFE58A5A,
};
function col(v) {
  if (v === undefined || v === null) return 'null';
  if (colorVars[v] !== undefined) return '0x' + colorVars[v].toString(16).toUpperCase().padStart(8, '0');
  if (/^#[0-9a-f]{6}$/i.test(v)) return '0xFF' + v.slice(1).toUpperCase();
  throw new Error('unknown color ' + v);
}
function s(v) {
  return "'" + String(v).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$').replace(/\n/g, '\\n').replace(/\r/g, '\\r').replace(/\t/g, '\\t') + "'";
}
function list(arr) { return '[' + arr.map(s).join(', ') + ']'; }
function re(r) {
  const src = r.source.replace(/\\\//g, '/');
  if (src.includes("'''")) throw new Error('regex has triple quote');
  return "RegExp(r'''" + src + "'''" + (r.flags.includes('i') ? ', caseSensitive: false' : '') + ')';
}
const out = [];
const p = x => out.push(x);
p('// GENERATED by tool/gen_constants.js from the original PromptForge.html - do not edit by hand.');
p("import '../domain/models.dart';");
p("import 'constants.dart';");
p('');
p('const List<CategoryDef> kCategories = [');
for (const c of C.CATEGORIES) p(`  CategoryDef(${s(c.id)}, ${s(c.label)}, ${col(c.color)}),`);
p('];\n');
p('const List<StatusDef> kStatuses = [');
for (const c of C.PROMPT_STATUSES) p(`  StatusDef(${s(c.id)}, ${s(c.label)}, ${col(c.color)}),`);
p('];\n');
p('const List<BlockType> kBlockTypes = [');
for (const b of C.BLOCK_TYPES) p(`  BlockType(${s(b.id)}, ${s(b.label)}, ${col(b.color)}, ${s(b.placeholder)}),`);
p('];\n');
p('const List<String> kDefaultBuilderOrder = ' + list(C.DEFAULT_BUILDER_ORDER) + ';\n');
p('const List<BuilderPreset> kBuilderPresets = [');
for (const st of C.BUILDER_STRUCTURES) {
  p(`  BuilderPreset(${s(st.id)}, ${s(st.name)}, [`);
  for (const b of st.blocks) p(`    BlockDef(${s(b.type)}${b.label ? ', label: ' + s(b.label) : ''}${b.color ? ', color: ' + col(b.color) : ''}),`);
  p('  ]),');
}
p('];\n');
p('const List<ModelSpec> kModels = [');
for (const m of C.MODELS) p(`  ModelSpec(id: ${s(m.id)}, label: ${s(m.label)}, vendor: ${s(m.vendor)}, group: ${s(m.group)}, charsPerToken: ${m.charsPerToken}, contextWindow: ${m.contextWindow}, priceIn: ${Number(m.priceIn).toFixed(2)}, priceOut: ${Number(m.priceOut).toFixed(2)}, priceNote: ${s(m.priceNote)}, idiomKey: ${s(m.idiomKey)}, tokenizer: ${s(m.tokenizer)}),`);
p('];\n');
p('const Map<String, ModelIdiom> kModelIdioms = {');
for (const [k, v] of Object.entries(C.MODEL_IDIOMS)) p(`  ${s(k)}: ModelIdiom(${s(v.label)}, ${s(v.comparative)}, ${list(v.tips)}),`);
p('};\n');
p('const List<ScoringProfile> kScoringProfiles = [');
for (const sp of C.SCORING_PROFILES) {
  const w = sp.weights;
  p(`  ScoringProfile(${s(sp.id)}, ${s(sp.label)}, ScoreWeights(clarity: ${w.clarity}, context: ${w.context}, specificity: ${w.specificity}, structure: ${w.structure}, constraints: ${w.constraints}, output: ${w.output}, ambiguity: ${w.ambiguity})),`);
}
p('];\n');
p('const List<String> kLearnTips = ' + list(C.LEARN_TIPS) + ';\n');
p('const List<Challenge> kChallenges = [');
for (const c of C.CHALLENGES) p(`  Challenge(${s(c.id)}, ${s(c.level)}, ${s(c.title)}, ${s(c.prompt)}, ${s(c.task)}, ${list(c.checkKeywords)}),`);
p('];\n');
p('const List<ConstraintAtom> kConstraintLibrary = [');
for (const c of C.CONSTRAINT_LIBRARY) p(`  ConstraintAtom(${s(c.id)}, ${s(c.category)}, ${s(c.label)}, ${s(c.text)}),`);
p('];\n');
p('const List<EdgeCaseItem> kEdgeCaseChecklist = [');
for (const c of C.EDGE_CASE_CHECKLIST) p(`  EdgeCaseItem(${s(c.id)}, ${s(c.label)}, ${s(c.question)}),`);
p('];\n');
p('final List<PromptPattern> kPatterns = [');
for (const x of C.PATTERNS) p(`  PromptPattern(id: ${s(x.id)}, name: ${s(x.name)}, category: ${s(x.category)}, purpose: ${s(x.purpose)}, when: ${s(x.when)}, template: ${s(x.template)}, example: ${s(x.example)}, variables: ${list(x.variables)}, builtin: true, createdAt: 0, updatedAt: 0),`);
p('];\n');
p('final List<SecurityPattern> kSecurityPatterns = [');
for (const x of C.SECURITY_PATTERNS) p(`  SecurityPattern(${s(x.id)}, ${s(x.label)}, ${re(x.re)}),`);
p('];\n');
p('final List<RiskPattern> kRiskPatterns = [');
for (const x of C.RISK_PATTERNS) p(`  RiskPattern(${s(x.id)}, ${s(x.label)}, ${re(x.re)}, ${s(x.detail)}),`);
p('];\n');
p('const List<Persona> kPersonas = [');
for (const x of PERSONAS) p(`  Persona(${s(x.id)}, ${s(x.label)}, ${s(x.text)}),`);
p('];\n');
p('const List<Persona> kAudiences = [');
for (const x of AUDIENCES) p(`  Persona(${s(x.id)}, ${s(x.label)}, ${s(x.text)}),`);
p('];\n');
p('const List<int> kGroupColors = [' + C.GROUP_COLORS.map(c => col(c)).join(', ') + '];\n');
console.log(out.join('\n'));
